import yaml

from cosmos_framework.evaluation.robodojo_sr_protocol import (
    EPISODES_PER_FAMILY,
    TOTAL_EPISODES,
    evaluation_cells,
    native_prefix_metrics,
)

REPO = Path(os.environ["ROBODOJO_EVAL_REPO"])
RUN = Path(os.environ["ROBODOJO_EVAL_RUN"])
CONTROL = RUN / "control/eval"
STEP = int(os.environ["ROBODOJO_EVAL_STEP"])
FINISH = json.loads((RUN / f"continuation/evaluation_targets/step{STEP:06d}.json").read_text())
if int(FINISH["final_step"]) != STEP:
    raise ValueError("Evaluation target and pinned checkpoint step disagree")
OUT = RUN / f"continuation/evaluations/step{STEP:06d}"
BENCH = Path(os.environ["ROBODOJO_BENCH_ROOT"])
POLICY = BENCH / "XPolicyLab/policy/Cosmos3_Edge_RoboDojo_ViT"
TRAIN = Path(FINISH["snapshot_train_dir"])
CAMERAS = ("cam_head", "cam_left_wrist", "cam_right_wrist")
FAMILIES = ("classify_objects", "stack_bowls", "push_T", "insert_tubes")
CELLS = evaluation_cells()

STEPS = {
    "classify_objects": 1100,
    "insert_tubes": 500,
    "stack_bowls": 800,
    "stack_bowls_random": 800,
    "push_T": 600,
    "push_T_random": 600,
}
PREFIX = f"{RUN.name}_vit_step{STEP}"
VIDEO_RE = re.compile(r"episode_(\d+)_(cam_head|cam_left_wrist|cam_right_wrist)_(success|fail)\.mp4")


def atomic(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(".tmp")
    temporary.write_text(json.dumps(value, ensure_ascii=False, indent=2, allow_nan=False) + "\n")
    temporary.replace(path)


def keep_count(task, seed):
    if task in ("classify_objects", "insert_tubes"):
        return 2 if seed < 2 else 1
    return 1 if seed < 2 or not task.endswith("_random") else 0


def run_id(task, seed):
    return f"{PREFIX}_{task}_seed{seed}"


def result_path(task, seed):
    base = BENCH / "eval_result/RoboDojo" / task / "Cosmos3_Edge_RoboDojo_ViT/arx_x5"
    paths = list(base.glob(f"*/{run_id(task, seed)}/_result.json"))
    if len(paths) > 1:
        raise ValueError(f"Ambiguous results for {task}/{seed}: {paths}")
    return paths[0] if paths else None


def retain_videos(directory, completed, keep, expected_run_id, *, result_root=None):
    """Prune only finalized, committed videos generated by this new run."""
    root = (result_root or BENCH / "eval_result").resolve()
    if directory.name != expected_run_id or not directory.resolve().is_relative_to(root):
        raise ValueError(f"Refusing video pruning outside the isolated run: {directory}")
    selected = {}
    for path in directory.glob("episode_*.mp4"):
        match = VIDEO_RE.fullmatch(path.name)
        if not match:
            continue
        episode, camera, outcome = match.groups()
        index = int(episode)
        if index >= completed:
            continue  # current episode may be finalized before its metrics commit
        if index >= keep:
            path.unlink(missing_ok=True)
        else:
            item = selected.setdefault(index, {"episode": index, "outcome": outcome, "cameras": {}})
            item["cameras"][camera] = str(path)
    return [item for _, item in sorted(selected.items()) if set(item["cameras"]) == set(CAMERAS)]


def assignments():
    cells = [[] for _ in range(8)]
    loads = [0] * 8
    for cell in sorted(CELLS, key=lambda x: x[2] * STEPS[x[0]], reverse=True):
        index = min(range(8), key=lambda i: (loads[i], len(cells[i]), i))
        cells[index].append(cell)
        loads[index] += cell[2] * STEPS[cell[0]]
    return cells


def initialize():
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "logs").mkdir(exist_ok=True)
    checkpoint = TRAIN / "checkpoints" / f"iter_{STEP:09d}"
    if not (checkpoint / "model/.metadata").is_file():
        raise ValueError(f"Step {STEP} checkpoint is incomplete")
    if yaml.safe_load((POLICY / "deploy.yml").read_text())["eval_batch"] is not False:
        raise ValueError("Only the verified one-environment camera path is supported")
    config_path = OUT / "config.yaml"
    if not config_path.exists():
        config = yaml.safe_load((TRAIN / "config.yaml").read_text())
        config["checkpoint"].update(
            load_path=str(checkpoint), keys_to_skip_loading=[], load_training_state=False, load_ema_to_reg=True
        )
        config_path.write_text(yaml.safe_dump(config, sort_keys=False))
    deploy = yaml.safe_load((POLICY / "deploy.yml").read_text())
    deploy.update(
        checkpoint_path=str(checkpoint),
        config_file=str(config_path),
        output_dir=str(OUT / "policy"),
        eval_batch=False,
        num_steps=30,
    )
    (OUT / "deploy.yml").write_text(yaml.safe_dump(deploy, sort_keys=False))
    manifest = {
        "checkpoint": str(checkpoint),
        "step": STEP,
        "arm": "joint480_reasoner_vit",
        "weights": "EMA",
        "config_file": str(config_path),
        "config_sha256": hashlib.sha256(config_path.read_bytes()).hexdigest(),
        "episodes_per_family": EPISODES_PER_FAMILY,
        "episodes": TOTAL_EPISODES,
        "seeds": [0, 1, 2],
        "episodes_per_family_per_seed": 5,
        "protocol_version": "sr15_seed3x5_v1",
        "initial_states": "Official pre-generated test layouts, ordered within seed; first valid episodes per fixed quota",
        "selection_policy": "First valid episodes per fixed seed/variant quota, independent of outcome; native history may contain more episodes",
        "num_envs_per_client": 1,
        "guidance": 1.0,
        "denoising_steps": 30,
        "action_chunk": 16,
        "fps": 25,
        "raw_action_dim": 14,
        "resolution_tier": "480",
        "canvas_wh": [736, 544],
        "training_shift": 5,
        "retained_episodes_per_family": 5,
        "cameras_per_episode": list(CAMERAS),
        "video_selection": "First 2/2/1 episodes across seeds for classify/insert; first standard episode in each seed plus first random episode in seeds 0 and 1 for stack/push. Selection is fixed before outcomes.",
        "cells": [
            {"task": t, "seed": s, "quota": q, "run_id": run_id(t, s), "keep": keep_count(t, s)} for t, s, q in CELLS
        ],
    }
    atomic(OUT / "manifest.json", manifest)
    public = OUT / "public"
    public.mkdir(exist_ok=True)
    link = RUN / "continuation/public" / f"step{STEP:06d}"
    if not link.exists():
        link.symlink_to(public, target_is_directory=True)
    publish()


def publish():
    public = OUT / "public"
    public.mkdir(parents=True, exist_ok=True)
    with (OUT / ".publish.lock").open("a") as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        manifest = json.loads((OUT / "manifest.json").read_text())
        families = {
            family: {"episodes": 0, "target": EPISODES_PER_FAMILY, "successes": 0, "score_sum": 0, "videos": []}
            for family in FAMILIES
        }
        cells = []
        for task, seed, quota in CELLS:
            path = result_path(task, seed)
            if not path:
                continue
            try:
                native = json.loads(path.read_text())
            except json.JSONDecodeError:
                continue
            metrics = native_prefix_metrics(native, quota)
            completed = metrics["episodes"]
            successes = metrics["successes"]
            family = task.removesuffix("_random")
            item = families[family]
            item["episodes"] += completed
            item["successes"] += successes
            item["score_sum"] += float(metrics["score"] or 0) * completed
            clips = retain_videos(path.parent, completed, keep_count(task, seed), run_id(task, seed))
            for clip in clips:
                media = public / "media" / task / f"seed{seed}"
                media.mkdir(parents=True, exist_ok=True)
                sources = clip["cameras"]
                urls = {}
                for camera, filename in sources.items():
                    source = Path(filename)
                    dest = media / source.name
                    if not dest.exists():
                        dest.symlink_to(source)
                    urls[camera] = str(dest.relative_to(public))
                item["videos"].append({**clip, "task": task, "seed": seed, "cameras": urls})
            cells.append(
                {
                    "task": task,
                    "seed": seed,
                    "episodes": completed,
                    "target": quota,
                    "successes": successes,
                    "success_rate": successes / completed if completed else None,
                    "score": metrics["score"],
                    "native_episodes": metrics["native_episodes"],
                    "selected_episode_indices": metrics["selected_episode_indices"],
                    "selected_layout_ids": metrics["selected_layout_ids"],
                    "result_path": str(path),
                    "complete": completed == quota,
                }
            )
            native_dir = public / "native_results"
            native_dir.mkdir(exist_ok=True)
            dest = native_dir / f"{task}_seed{seed}.json"
            if not dest.exists():
                dest.symlink_to(path)
        for item in families.values():
            item["success_rate"] = item["successes"] / item["episodes"] if item["episodes"] else None
            score_sum = item.pop("score_sum")
            item["score"] = score_sum / item["episodes"] if item["episodes"] else None
            item["videos"].sort(key=lambda x: (x["seed"], x["task"], x["episode"]))
            if len(item["videos"]) > 5:
                raise ValueError("Video retention exceeded five per family")
        episodes = sum(item["episodes"] for item in families.values())
        submission = json.loads((OUT / "submission.json").read_text()) if (OUT / "submission.json").exists() else None
        job_states = []
        if submission:
            query = subprocess.run(
                [
                    "sacct",
                    "-X",
                    "-n",
                    "-P",
                    "-j",
                    ",".join(job["job_id"] for job in submission["jobs"]),
                    "--format=JobID,State,Elapsed",
                ],
                capture_output=True,
                text=True,
            )
            if query.returncode == 0:
                for line in query.stdout.splitlines():
                    identifier, state, elapsed, *_ = line.split("|")
                    job_states.append({"job_id": identifier, "state": state, "elapsed": elapsed})
        report = {
            "updated_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
            "manifest": manifest,
            "episodes": episodes,
            "target": TOTAL_EPISODES,
            "complete": episodes == TOTAL_EPISODES,
            "families": families,
            "cells": cells,
            "submission": submission,
            "job_states": job_states,
        }
        atomic(public / "report.json", report)
        atomic(OUT / "results.json", report)
        text = io.StringIO()
        writer = csv.DictWriter(text, fieldnames=["task", "episodes", "target", "successes", "success_rate", "score"])
        writer.writeheader()
        writer.writerows({"task": t, **{k: v for k, v in row.items() if k != "videos"}} for t, row in families.items())
        (public / "success_rates.csv").write_text(text.getvalue())
        (public / "index.html").write_text((CONTROL / "results.html").read_text())
        return report


def worker(index):
    deadline = float(os.environ["ROBODOJO_SR_DEADLINE"])
    for task, seed, quota in assignments()[index]:
        path = result_path(task, seed)
        if path and json.loads(path.read_text()).get("eval_time", 0) >= quota:
            continue
        if time.time() > deadline - 90:
            break
        env = dict(os.environ, EVAL_NUM=str(quota), EVAL_ENV_TYPE="sim", ROBODOJO_RUN_ID=run_id(task, seed))
        command = [
            "bash",
            str(CONTROL / "cell.sh"),
            str(OUT),
            task,
            str(seed),
            str(2 * (index % 4)),
            str(2 * (index % 4) + 1),
        ]
        with (OUT / "logs" / f"{task}_seed{seed}.log").open("a") as stream:
            process = subprocess.Popen(
                command, env=env, stdout=stream, stderr=subprocess.STDOUT, start_new_session=True
            )
            try:
                while True:
                    try:
                        code = process.wait(timeout=max(1, min(60, deadline - time.time())))
                        break
                    except subprocess.TimeoutExpired:
                        publish()
                        if time.time() >= deadline:
                            raise
            except subprocess.TimeoutExpired:
                os.killpg(process.pid, signal.SIGTERM)
                try:
                    process.wait(timeout=30)
                except subprocess.TimeoutExpired:
                    os.killpg(process.pid, signal.SIGKILL)
                    process.wait()
                print(f"DEADLINE: cell {task}/{seed} will resume from native manifest", flush=True)
                return
        if code:
            raise RuntimeError(f"Native evaluation failed for {task}/{seed}: exit {code}")
        path = result_path(task, seed)
        if not path or json.loads(path.read_text()).get("eval_time", 0) < quota:
            raise ValueError(f"Native quota incomplete for {task}/{seed}")
        publish()


def launch():
    rank = int(os.environ.get("SLURM_PROCID", "0"))
    active = []
    for local in range(4):
        stream = (OUT / "logs" / f"worker_{rank * 4 + local}_{os.environ['SLURM_JOB_ID']}.log").open("a")
        active.append(
            (
                subprocess.Popen(
                    [sys.executable, __file__, "--worker", str(rank * 4 + local)],
                    stdout=stream,
                    stderr=subprocess.STDOUT,
                ),
                stream,
            )
        )
    codes = []
    for process, stream in active:
        codes.append(process.wait())
        stream.close()
    if any(codes):
        raise RuntimeError(f"Worker failures on node rank {rank}: {codes}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--initialize", action="store_true")
    parser.add_argument("--publish", action="store_true")
    parser.add_argument("--worker", type=int)
    parser.add_argument("--finish", type=int)
    args = parser.parse_args()
    if args.initialize:
        initialize()
    elif args.publish:
        publish()
    elif args.worker is not None:
        worker(args.worker)
    elif args.finish is not None:
        report = publish()
        atomic(
            OUT / f"phase_{args.finish}_status.json",
            {"episodes": report["episodes"], "complete": report["complete"], "job_id": os.environ["SLURM_JOB_ID"]},
        )
        if report["complete"]:
            for family, row in report["families"].items():
                if len(row["videos"]) != 5:
                    raise ValueError(f"Incomplete retained video coverage: {family}")
        print(
            json.dumps({k: {n: v for n, v in row.items() if n != "videos"} for k, row in report["families"].items()}),
            flush=True,
        )
    else:
        launch()
